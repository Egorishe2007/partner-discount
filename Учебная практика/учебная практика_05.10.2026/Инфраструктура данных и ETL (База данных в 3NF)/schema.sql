-- Хранилище CRM «Партнеры и продажи»: PostgreSQL, третья нормальная форма.
-- Имена — snake_case, таблицы во множественном числе, ограничения названы
-- явно: по имени из сообщения СУБД сразу видно, какое правило нарушено.
-- Скрипт можно запускать повторно: таблицы удаляются в обратном порядке
-- зависимостей, иначе удаление не пропустят внешние ключи.

SET client_encoding = 'UTF8';

DROP TABLE IF EXISTS sales_history;
DROP TABLE IF EXISTS products;
DROP TABLE IF EXISTS partners;

-- Партнер. Организационно-правовая форма хранится отдельно от названия:
-- «ООО "Вектор"» — это два факта, а не одно значение (1НФ).
-- Директор, телефон и адрес в исходных файлах не пришли, поэтому
-- необязательны: менеджер заполнит их в карточке партнера.
CREATE TABLE partners (
    id            INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    partner_type  VARCHAR(3)    NOT NULL,
    name          VARCHAR(255)  NOT NULL,
    inn           VARCHAR(12)   NOT NULL,
    email         VARCHAR(255)  NOT NULL,
    director      VARCHAR(255),
    phone         VARCHAR(20),
    legal_address VARCHAR(500),
    rating        INTEGER       NOT NULL DEFAULT 0,
    CONSTRAINT partners_pk PRIMARY KEY (id),
    CONSTRAINT partners_inn_uk UNIQUE (inn),
    CONSTRAINT partners_email_uk UNIQUE (email),
    CONSTRAINT partners_type_ck
        CHECK (partner_type IN ('ООО', 'АО', 'ЗАО', 'ОАО', 'ПАО', 'ИП')),
    CONSTRAINT partners_inn_ck CHECK (inn ~ '^([0-9]{10}|[0-9]{12})$'),
    CONSTRAINT partners_email_ck CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]{2,}$'),
    CONSTRAINT partners_rating_ck CHECK (rating >= 0)
);

-- Справочник номенклатуры. Цена — DECIMAL: деньги нельзя хранить во
-- float, иначе 0,1 + 0,2 перестанет быть равно 0,3.
CREATE TABLE products (
    id    INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    name  VARCHAR(255)   NOT NULL,
    price DECIMAL(12, 2) NOT NULL,
    CONSTRAINT products_pk PRIMARY KEY (id),
    CONSTRAINT products_name_uk UNIQUE (name),
    CONSTRAINT products_price_ck CHECK (price >= 0)
);

-- История реализации: кто, что, когда и сколько купил.
-- Сумма — факт сделки: со скидкой партнера она может отличаться от
-- цены справочника, поэтому хранится, а не вычисляется из price.
CREATE TABLE sales_history (
    id         INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    partner_id INTEGER        NOT NULL,
    product_id INTEGER        NOT NULL,
    sale_date  DATE           NOT NULL,
    quantity   INTEGER        NOT NULL,
    amount     DECIMAL(12, 2) NOT NULL,
    CONSTRAINT sales_history_pk PRIMARY KEY (id),
    CONSTRAINT sales_history_partner_fk FOREIGN KEY (partner_id)
        REFERENCES partners (id) ON DELETE RESTRICT,
    CONSTRAINT sales_history_product_fk FOREIGN KEY (product_id)
        REFERENCES products (id) ON DELETE RESTRICT,
    CONSTRAINT sales_history_quantity_ck CHECK (quantity > 0),
    CONSTRAINT sales_history_amount_ck CHECK (amount >= 0)
);

CREATE INDEX sales_history_partner_idx ON sales_history (partner_id);
CREATE INDEX sales_history_product_idx ON sales_history (product_id);
